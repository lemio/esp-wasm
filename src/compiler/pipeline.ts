import { elfToImage } from "../image/esp-image";
import { FLASH_OFFSETS } from "../image/flash-layout";
import type { Toolchain } from "./toolchain";
import type { BuildLibrary, BuildOptions, BuildResult, Diagnostic, LogLevel, SourceFile } from "./types";

/** Compiled library objects, kept for the worker's lifetime: key → object file. */
const libraryObjects = new Map<string, Uint8Array>();

/** FNV-1a, to keep object cache keys short. */
function hash(text: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 0x01000193);
  return (h >>> 0).toString(16);
}

/** Compiled objects persist in the browser database (gzip), so a library compiles once, not per session. */
async function cachedObject(key: string): Promise<Uint8Array | undefined> {
  try {
    const blob = await dbRequest(OBJECTS, "readonly", (s) => s.get(key) as IDBRequest<Blob | undefined>);
    return blob ? await gunzipBlob(blob) : undefined;
  } catch {
    return undefined; // no IndexedDB (e.g. private mode): compile instead
  }
}
async function storeObject(key: string, data: Uint8Array): Promise<void> {
  try {
    const blob = await gzip(data);
    await dbRequest(OBJECTS, "readwrite", (s) => s.put(blob, key));
  } catch { /* best effort */ }
}
const libRoot = (lib: BuildLibrary) => `/libs/${lib.id.replace(/[^A-Za-z0-9_.-]/g, "_")}`;
const LIB_SOURCE = /\.(c|cc|cpp|cxx|S)$/;

/** Trace builds: instrument basic blocks, keep line tables, and optimize lightly so lines map cleanly. */
const TRACE_FLAGS = ["-fsanitize-coverage=trace-pc", "-Og", "-gdwarf-4", "-gline-tables-only"];
const TRACE_RUNTIME = "__esp_wasm_trace.cpp";
import { buildLineTable } from "../debug/line-table";
import { addStatementHooks } from "../debug/statement-hooks";
import traceRuntime from "../debug/trace-runtime.cpp?raw";
import { parseElf } from "../image/elf";
import { OBJECTS, dbRequest, gunzipBlob, gzip } from "../libraries/db";
import { COMPAT_DIR, COMPAT_HEADERS } from "./compat-headers";
import { addPrototypes } from "./prototypes";
import { runWasi } from "./wasi-runner";

/**
 * Flag files inside the sysroot (generated by toolchain/build-sysroot.sh):
 *   flags/common.txt  include dirs, defines, -mcpu/-mlongcalls… (shared by C and C++)
 *   flags/c.txt       C-only flags (-std=gnu17 …)
 *   flags/cxx.txt     C++-only flags (-std=gnu++2b …)
 *   flags/link.txt    linker args; @OBJECTS@ and @OUTPUT@ are substituted
 * One argument per line; blank lines and lines starting with # are ignored.
 */
function readArgs(tc: Toolchain, name: string): string[] {
  const text = tc.vfs.readText(`sysroot/flags/${name}`);
  if (text === undefined) throw new Error(`sysroot is missing flags/${name}`);
  return text.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));
}

const DIAG_RE = /^(.+?):(\d+):(\d+): (fatal error|error|warning|note): (.*)$/;

export function parseDiagnostics(stderr: string): Diagnostic[] {
  return stderr.split("\n").flatMap((line) => {
    const m = DIAG_RE.exec(line);
    if (!m) return [];
    return [{
      file: m[1],
      line: Number(m[2]),
      column: Number(m[3]),
      severity: (m[4] === "fatal error" ? "error" : m[4]) as Diagnostic["severity"],
      message: m[5],
    }];
  });
}

export class BuildError extends Error {
  /** output: the compiler's messages, for the page to show (or replace with a suggestion). */
  constructor(message: string, readonly diagnostics: Diagnostic[] = [], readonly output = "") {
    super(message);
  }
}

type Log = (text: string, level?: LogLevel) => void;

export async function build(
  tc: Toolchain,
  userSources: SourceFile[],
  log: Log,
  { defines = [], trace = false, libraries = [] }: BuildOptions = {},
): Promise<BuildResult> {
  // The trace runtime is compiled as-is (not instrumented) next to the user's code.
  const sources = trace ? [...userSources, { path: TRACE_RUNTIME, content: traceRuntime }] : userSources;
  const start = performance.now();
  const { vfs } = tc;
  vfs.resetDir("src");
  vfs.resetDir("build");
  vfs.resetDir("libs");
  vfs.resetDir(COMPAT_DIR.slice(1));
  for (const [path, content] of Object.entries(COMPAT_HEADERS)) vfs.writeFile(`${COMPAT_DIR.slice(1)}/${path}`, content);
  for (const lib of libraries) {
    for (const f of lib.files) vfs.writeFile(`${libRoot(lib).slice(1)}/${f.path}`, f.content);
  }
  // Installed libraries' headers are visible to the sketch and to each other.
  const libIncludes = [
    // -isystem: warnings inside third-party headers don't flood the sketch's output.
    ...libraries.flatMap((lib) => lib.includeDirs.flatMap((d) => ["-isystem", `${libRoot(lib)}${d === "." ? "" : `/${d}`}`])),
    // Stand-ins for headers ESP-IDF 6 removed; searched last.
    `-idirafter${COMPAT_DIR}`,
  ];
  const isSketch = sources.some((s) => s.path.endsWith(".ino"));
  for (const s of sources) {
    // Sketches get Arduino-style prototypes, so functions can be used before they're defined.
    let content = s.path.endsWith(".ino") ? addPrototypes(s.content, `/src/${s.path}`) : s.content;
    // Trace builds: a hook on every statement line, not just every basic block.
    if (trace && s.path !== TRACE_RUNTIME && /\.(ino|cpp|cc|cxx|c)$/.test(s.path)) {
      content = addStatementHooks(content, `/src/${s.path}`, s.path.endsWith(".c"));
    }
    vfs.writeFile(`src/${s.path}`, content);
  }

  const common = readArgs(tc, "common.txt");
  const cflags = readArgs(tc, "c.txt");
  const cxxflags = readArgs(tc, "cxx.txt");
  const diagnostics: Diagnostic[] = [];
  const objects: string[] = [];

  // 1. Compile. One clang process per translation unit, since WASI can't fork.
  for (const src of sources) {
    const ext = src.path.split(".").pop()!.toLowerCase();
    if (!["c", "cpp", "cc", "cxx", "s", "ino"].includes(ext)) continue;
    const obj = `/build/${src.path.replaceAll("/", "__")}.o`;
    // .ino: an Arduino sketch, which is C++ with Arduino.h included implicitly
    // (as the Arduino IDE does).
    // Arduino code is written for GCC, where narrowing in braces is a warning;
    // clang makes it an error by default.
    const cxx = [...cxxflags, "-Wno-c++11-narrowing"];
    const langFlags = ext === "c" ? cflags
      : ext === "s" ? []
      : ext === "ino" ? [...cxx, "-x", "c++", "-include", "Arduino.h"]
      : cxx;
    if (src.path !== TRACE_RUNTIME) log(`CC ${src.path}`, "muted");
    const res = await runWasi(tc.clang, [
      tc.manifest.tools.clang.argv0,
      ...common,
      ...langFlags,
      ...defines.map((d) => `-D${d}`),
      ...libIncludes,
      ...(trace && src.path !== TRACE_RUNTIME ? TRACE_FLAGS : []),
      // The runtime takes debugger commands over Serial in Arduino sketches.
      ...(trace && src.path === TRACE_RUNTIME && isSketch ? ["-DESP_WASM_ARDUINO=1"] : []),
      "-fno-color-diagnostics",
      "-c", `/src/${src.path}`,
      "-o", obj,
    ], vfs);
    diagnostics.push(...parseDiagnostics(res.stderr));
    if (res.exitCode !== 0) throw new BuildError(`Compilation of ${src.path} failed`, diagnostics, res.stderr);
    if (res.stderr) log(res.stderr, "info"); // warnings
    objects.push(obj);
  }
  if (objects.length === 0) throw new BuildError("No source files to compile");

  // 1b. Installed libraries, linked after the user's objects. Each object is
  // compiled once: cached in memory and in the browser database, keyed by
  // library version, toolchain version, file and flags.
  const flagsHash = hash([tc.manifest.version, ...defines, ...libIncludes].join(" "));
  for (const lib of libraries) {
    const sources = lib.files.filter((x) => LIB_SOURCE.test(x.path));
    let compiled = 0;
    for (const f of sources) {
      const key = `${lib.id}@${lib.version}|${flagsHash}|${f.path}`;
      const obj = `/build/lib${objects.length}.o`;
      let data = libraryObjects.get(key) ?? (await cachedObject(key));
      if (!data) {
        if (compiled === 0) log(`Compiling library ${lib.id} (${sources.length} files, once; then it's cached)…`, "muted");
        compiled++;
        if (compiled % 50 === 0) log(`  ${compiled}/${sources.length}`, "muted");
        const isC = f.path.endsWith(".c");
        const res = await runWasi(tc.clang, [
          tc.manifest.tools.clang.argv0,
          ...common,
          ...(isC ? cflags : [...cxxflags, "-Wno-c++11-narrowing"]),
          ...defines.map((d) => `-D${d}`),
          ...libIncludes,
          "-w", // third-party code: don't flood the output with its warnings
          "-fno-color-diagnostics",
          "-c", `${libRoot(lib)}/${f.path}`,
          "-o", obj,
        ], vfs);
        diagnostics.push(...parseDiagnostics(res.stderr));
        if (res.exitCode !== 0) {
          throw new BuildError(`Compiling library ${lib.id} (${f.path}) failed`, diagnostics, res.stderr);
        }
        data = vfs.readFile(obj)!.slice();
        await storeObject(key, data);
      } else {
        vfs.writeFile(obj.slice(1), data);
      }
      libraryObjects.set(key, data);
      objects.push(obj);
    }
  }

  // 2. Link against the precompiled ESP-IDF sysroot.
  const elfPath = "/build/app.elf";
  const linkArgs = readArgs(tc, "link.txt").flatMap((a) =>
    a === "@OBJECTS@" ? objects : [a.replace("@OUTPUT@", elfPath)],
  );
  log("LD app.elf", "muted");
  const ld = await runWasi(tc.ld, [tc.manifest.tools.ld.argv0, ...linkArgs], vfs);
  if (ld.stderr) log(ld.stderr, ld.exitCode ? "error" : "info");
  if (ld.exitCode !== 0) throw new BuildError("Linking failed", diagnostics);

  // 3. ELF → flashable app image.
  const elf = vfs.readFile(elfPath);
  if (!elf) throw new BuildError("Linker produced no output");
  const app = await elfToImage(elf, tc.manifest.image);
  const lineTable = trace
    ? buildLineTable(parseElf(elf).sections, elf, (f) => f.startsWith("/src/") && !f.endsWith(TRACE_RUNTIME))
    : undefined;

  return {
    parts: [
      { name: "bootloader.bin", address: FLASH_OFFSETS.bootloader, data: tc.bootloader },
      { name: "partition-table.bin", address: FLASH_OFFSETS.partitionTable, data: tc.partitionTable },
      { name: "app.bin", address: FLASH_OFFSETS.app, data: app },
    ],
    diagnostics,
    lineTable,
    elfSize: elf.length,
    durationMs: performance.now() - start,
  };
}
